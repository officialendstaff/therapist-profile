-- New per-interviewer availability; legacy staff_schedule_blocks remains unchanged.
create table if not exists public.interview_staff_unavailability (
 id bigint generated by default as identity primary key,
 interviewer_user_id uuid not null references public.interview_staff_assignments(user_id),
 block_date date not null,
 all_day boolean not null default false,
 start_time time,
 end_time time,
 created_at timestamptz not null default now(),
 constraint interview_staff_unavailability_valid_range check (
   (all_day and start_time is null and end_time is null) or
   (not all_day and start_time is not null and end_time is not null and start_time < end_time)
 )
);
create index if not exists interview_staff_unavailability_lookup on public.interview_staff_unavailability(interviewer_user_id,block_date);
alter table public.interview_staff_unavailability enable row level security;
create policy "availability readable for booking" on public.interview_staff_unavailability for select to anon,authenticated using (true);
create policy "availability owner insert" on public.interview_staff_unavailability for insert to authenticated
 with check (interviewer_user_id=auth.uid() and exists(select 1 from public.interview_staff_assignments a where a.user_id=auth.uid()));
create policy "availability owner update" on public.interview_staff_unavailability for update to authenticated
 using (interviewer_user_id=auth.uid()) with check (interviewer_user_id=auth.uid());
create policy "availability owner delete" on public.interview_staff_unavailability for delete to authenticated
 using (interviewer_user_id=auth.uid());
